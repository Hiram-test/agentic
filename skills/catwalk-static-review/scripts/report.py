    w.p('初始应力包含1123单元×8积分点=8984条六分量张量记录。每工况独立从初应力状态开始；P1一静力步，P2—P6先恒载步再目标组合步，均采用NLGEOM。第一步未显式给时间参数；第二步为1,1,1e-6,1。')
