    w.p('本次不输出可用于下料的无应力长度。近似L0=L/(1+N/(EA)+αΔT)仅适用于相容的小弹性应变口径；这里有预应力和有限变形，未单独验证应力度量、参考几何及索鞍修正，不能据此声称复现原报告表1-10/1-13。')
    w.h('2.4.4 猫道承重索强度验算',3)
    add_forces(w,rows,'bottom')
