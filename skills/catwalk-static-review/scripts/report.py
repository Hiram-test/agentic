    w.h('1.3 主要规范与复核口径',2)
    w.p('原报告采用 JTG D60-2015、JTG D64-2015、JTG/T 3650-2020、JTG/T 3360-01-2018、JTG/T D65-05-2015、GB 50017-2017、GB/T 20118-2025、GB 8918-2006、GB/T 33943-2017。这里只转录原报告依据，未宣称逐条重新验证全部规范。')
