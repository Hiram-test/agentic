    w.p('单位体系为 mm、N、s、tonne、MPa。重力加速度9806 mm/s²，方向(0,0,-1)，施加于E_CABLE与E_FRAME。下表仅统计各步CLOAD，不含DLOAD自重。第二步数据为总荷载，不再额外加一次第一步CLOAD。')
