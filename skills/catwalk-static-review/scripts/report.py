    w.p('P4/P5 有横向风力但所有UY被约束，横向力主要进入约束反力；本次不提供横风位移或三维抗风安全结论。原报告基本风速34.3 m/s、施工风速13.8 m/s，仅作来源说明，不再重复换算并叠加载荷。')
    w.page();w.h('第 2 章 猫道及门架承重索计算')
